let currentLang = localStorage.getItem("portfolio_lang") || "pt";

function setLanguage(lang) {
  if (!translations[lang]) return;
  currentLang = lang;
  localStorage.setItem("portfolio_lang", lang);
  document.documentElement.lang = lang === "pt" ? "pt-BR" : "en";

  // Update page title & meta description
  if (translations[lang].page_title) {
    document.title = translations[lang].page_title;
  }
  const metaDesc = document.querySelector('meta[name="description"]');
  if (metaDesc && translations[lang].meta_description) {
    metaDesc.setAttribute("content", translations[lang].meta_description);
  }

  // Update text content for elements with data-i18n
  document.querySelectorAll("[data-i18n]").forEach((el) => {
    const key = el.getAttribute("data-i18n");
    if (translations[lang][key]) {
      el.textContent = translations[lang][key];
    }
  });

  // Update innerHTML for elements with data-i18n-html (supports tags like <strong>, <em>, <br>)
  document.querySelectorAll("[data-i18n-html]").forEach((el) => {
    const key = el.getAttribute("data-i18n-html");
    if (translations[lang][key]) {
      el.innerHTML = translations[lang][key];
    }
  });

  // Update active state on language switcher buttons
  document.querySelectorAll(".lang-btn").forEach((btn) => {
    if (btn.getAttribute("data-lang") === lang) {
      btn.classList.add("active");
    } else {
      btn.classList.remove("active");
    }
  });
}

document.addEventListener("DOMContentLoaded", () => {
  // Initialize current language
  setLanguage(currentLang);

  // Attach click events to language buttons
  document.querySelectorAll(".lang-btn").forEach((btn) => {
    btn.addEventListener("click", (e) => {
      const selectedLang = e.currentTarget.getAttribute("data-lang");
      setLanguage(selectedLang);
    });
  });
});
